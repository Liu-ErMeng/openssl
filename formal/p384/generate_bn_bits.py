#!/usr/bin/env python3
"""Extract the 64-bit, non-e2k BN_num_bits_word program."""
import argparse
import re

from generate import HERE, body

SOURCE = HERE.parent.parent / "crypto/bn/bn_lib.c"


def stages(source):
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.S)
    fragment = body(source, "BN_num_bits_word")
    prefix = re.match(r"\s*BN_ULONG x, mask;\s*int bits = \(l != 0\);", fragment)
    if prefix is None:
        raise ValueError("Unmodeled BN_num_bits_word declarations")
    fragment = fragment[prefix.end():]
    guard = re.match(r"\s*#if BN_BITS2 > 32\s*", fragment)
    if guard is None or fragment.count("#endif") != 1:
        raise ValueError("Unexpected word-size selection")
    fragment = fragment[guard.end():].replace("#endif", "")
    step = re.compile(
        r"\s*x = l >> (\d+);\s*mask = \(0 - x\) & BN_MASK2;"
        r"\s*mask = \(0 - \(mask >> \(BN_BITS2 - 1\)\)\);"
        r"\s*bits \+= (\d+) & mask;"
        r"(\s*l \^= \(x \^ l\) & mask;)?")
    result, position = [], 0
    while match := step.match(fragment, position):
        shift, increment = int(match[1]), int(match[2])
        if not 0 < shift < 64:
            raise ValueError("Undefined or unsupported word-bit shift")
        result.append((shift, increment, bool(match[3])))
        position = match.end()
    if re.fullmatch(r"\s*return bits;\s*", fragment[position:]) is None:
        raise ValueError("Unmodeled BN_num_bits_word statements")
    if result != [(k, k, k != 1) for k in (32, 16, 8, 4, 2, 1)]:
        raise ValueError("Unexpected word-bit search stages")
    return result


def generate(source):
    lines = ["-- Generated by generate_bn_bits.py from BN_num_bits_word.",
             "import P384.WordSemantics", "", "set_option autoImplicit false", "",
             "namespace P384", "", "structure BNWordBitsTrace where",
             "  result : BitVec 32", "  counters : List (BitVec 32)", "",
             "def machineBNWordBitsTrace (input : BitVec 64) : BNWordBitsTrace :=",
             "  let b0 : BitVec 32 := if input = 0 then 0 else 1"]
    limb, count, counters = "input", "b0", ["b0"]
    for i, (shift, increment, update) in enumerate(stages(source)):
        lines.extend([
            f"  let x{i} := {limb} >>> {shift}",
            f"  let t{i} := ((0 : BitVec 64) - x{i}) &&& BitVec.allOnes 64",
            f"  let m{i} := (0 : BitVec 64) - (t{i} >>> 63)",
            f"  let b{i+1} := (({count}.signExtend 64) + (({increment} : BitVec 64) &&& m{i})).setWidth 32",
        ])
        if update:
            lines.append(f"  let l{i} := {limb} ^^^ ((x{i} ^^^ {limb}) &&& m{i})")
            limb = f"l{i}"
        count = f"b{i+1}"
        counters.append(count)
    lines.extend([f"  ⟨{count}, [{', '.join(counters)}]⟩", "",
                  "def machineBNNumBitsWord (input : BitVec 64) : BitVec 32 :=",
                  "  (machineBNWordBitsTrace input).result", "", "end P384", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = HERE / "P384/GeneratedBNWordBits.lean"
    generated = generate(SOURCE.read_text())
    if args.check:
        if output.read_text() != generated:
            raise SystemExit("BN word-bit source and model differ")
        print("BN word-bit source and extracted model match")
    else:
        output.write_text(generated)


if __name__ == "__main__":
    main()
