#!/usr/bin/env python3
"""Extract the complete supported felem_contract word program."""
import argparse
import ast
import re

from generate import HERE, SOURCE, body, vector


def contract_statements(source):
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.S)
    for pattern in (r"#define\s+NLIMBS\s+7\b", r"typedef\s+uint64_t\s+limb\s*;",
                    r"static\s+void\s+felem_contract\s*\(\s*felem\s+out,\s*const\s+felem\s+in\s*\)"):
        if re.search(pattern, source) is None:
            raise ValueError("Unmodeled contract type or signature")
    fragment = body(source, "felem_contract")
    prefix = re.match(
        r"\s*static const int64_t two56 = \(\(limb\)1\) << 56;"
        r"\s*int64_t tmp\[NLIMBS\], cond\[5\], a;\s*unsigned int i;"
        r"\s*memcpy\(tmp, in, sizeof\(felem\)\);", fragment)
    if prefix is None:
        raise ValueError("Unmodeled contract declarations or input copy")
    fragment = fragment[prefix.end():]
    loop = re.compile(r"\s*for \(i = 0; i < 5; i\+\+\)\s*cond\[i\] = ([^;]+);")
    assignment = re.compile(r"\s*(tmp\[[0-6]\]|cond\[[0-4]\]|a)\s*(\+=|-=|&=|=)\s*([^;]+);")
    steps, position = [], 0
    while position < len(fragment):
        if match := loop.match(fragment, position):
            for i in range(5):
                steps.append((f"cond[{i}]", "=", match[1].replace("[i]", f"[{i}]")))
        elif match := assignment.match(fragment, position):
            steps.append(match.groups())
        else:
            if re.fullmatch(r"\s*memcpy\(out, tmp, sizeof\(felem\)\);\s*", fragment[position:]):
                break
            raise ValueError("Unmodeled felem_contract statement")
        position = match.end()
    else:
        raise ValueError("Missing contract output copy")
    first = next(i for i, step in enumerate(steps) if step[0] == "cond[0]")
    after_conditions = first + 10
    if [s[0] for s in steps[first:after_conditions]] != [f"cond[{i}]" for i in range(5)] * 2:
        raise ValueError("Unexpected contract condition order")
    if len(steps) != 56 or first != 19:
        raise ValueError(f"Unexpected contract trace shape: {len(steps)}, {first}")
    return steps[:first], steps[first:after_conditions], steps[after_conditions:]


def expr(text):
    text = re.sub(r"\((?:int64_t|limb)\)", "", text)
    text = re.sub(r"\b(in|tmp|cond)\[(\d+)\]", r"\1_\2", text)
    return ast.parse(" ".join(text.split()), mode="eval").body


def translate(node, names):
    if isinstance(node, ast.Constant) and isinstance(node.value, int):
        return f"({node.value} : BitVec 64)"
    if isinstance(node, ast.Name):
        return names[node.id]
    if isinstance(node, ast.UnaryOp):
        op = {ast.Invert: "~~~", ast.USub: "-"}[type(node.op)]
        return f"({op}({translate(node.operand, names)}))"
    if isinstance(node, ast.BinOp):
        lhs = translate(node.left, names)
        if isinstance(node.op, (ast.LShift, ast.RShift)):
            amount = ast.literal_eval(node.right)
            if not 0 <= amount < 64:
                raise ValueError("Undefined contract shift")
            if isinstance(node.op, ast.LShift):
                return f"({lhs} <<< {amount})"
            if isinstance(node.left, ast.Name) and node.left.id.startswith("in_"):
                return f"({lhs} >>> {amount})"
            return f"(({lhs}).sshiftRight {amount})"
        op = {ast.Add: "+", ast.Sub: "-", ast.BitAnd: "&&&", ast.BitOr: "|||"}[type(node.op)]
        return f"({lhs} {op} {translate(node.right, names)})"
    raise ValueError(f"Unsupported contract expression: {ast.dump(node)}")


def emit(steps, name, initial, result):
    names = {f"in_{i}": f"input {i}" for i in range(7)}
    names.update({f"tmp_{i}": f"input {i}" for i in range(7)})
    names["two56"] = "(72057594037927936 : BitVec 64)"
    names.update(initial)
    lines, trace = [], []
    for index, (lhs, op, rhs) in enumerate(steps):
        key = re.sub(r"\[(\d+)\]", r"_\1", lhs)
        value = translate(expr(rhs), names)
        if op != "=":
            value = f"({names[key]} { {'+=': '+', '-=': '-', '&=': '&&&'}[op]} {value})"
        variable = f"s{index}"
        lines.append(f"  let {variable} := {value}")
        names[key] = variable
        trace.append(variable)
    if result == "tmp":
        value = vector([names[f"tmp_{i}"] for i in range(7)])
    else:
        value = vector([names[f"cond_{i}"] for i in range(5)])
    return [f"def {name} (input : LimbWords) : ContractWordTrace :=", *lines,
            f"  ⟨{value if result == 'tmp' else 'input'}, "
            f"{value if result == 'cond' else '(fun _ => 0)'}, [{', '.join(trace)}]⟩", ""]


def generate(source):
    first, conditions, tail = contract_statements(source)
    if first[6:] != tail[14:]:
        raise ValueError("Contract carry sequences differ")
    lines = ["-- Generated by generate_contract.py from felem_contract.",
             "import P384.GeneratedMachine", "", "set_option autoImplicit false", "",
             "namespace P384", "", "structure ContractWordTrace where",
             "  limbs : LimbWords", "  conditions : Fin 5 → BitVec 64", "  steps : List (BitVec 64)", ""]
    lines += emit(first, "machineContractFirstTrace", {}, "tmp")
    lines += emit(first[:6], "machineContractFoldTrace", {}, "tmp")
    lines += emit(first[6:], "machineContractCarryTrace", {}, "tmp")
    lines += emit(conditions, "machineContractConditionsTrace", {}, "cond")
    initial = {f"cond_{i}": f"(machineContractConditionsTrace input).conditions {i}" for i in range(5)}
    lines += emit(tail, "machineContractTailTrace", initial, "tmp")
    lines += emit(tail[:14], "machineContractSubtractTrace", initial, "tmp")
    lines += ["def machineContractFirst (input : LimbWords) : LimbWords :=",
              "  (machineContractFirstTrace input).limbs", "",
              "def machineContract (input : LimbWords) : LimbWords :=",
              "  (machineContractTailTrace (machineContractFirst input)).limbs", "",
              "end P384", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = SOURCE.read_text()
    output = HERE / "P384/GeneratedContract.lean"
    generated = generate(source)
    if args.check:
        if output.read_text() != generated:
            raise SystemExit("Contract source and model differ")
        print("Contract source and extracted word model match")
    else:
        output.write_text(generated)


if __name__ == "__main__":
    main()
