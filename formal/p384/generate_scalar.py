#!/usr/bin/env python3
"""Extract scalar helpers and bind the batch loop to its reviewed source."""
import argparse
import ast
import hashlib
import json
import re

from generate import HERE, SOURCE, body

UTIL = SOURCE.parent / "ecp_nistputil.c"


def clean(text):
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)


def recode_steps(source):
    fragment = body(clean(source), "ossl_ec_GFp_nistp_recode_scalar_bits")
    prefix = re.match(r"\s*unsigned char s, d;", fragment)
    if prefix is None:
        raise ValueError("Unexpected Booth declarations")
    position, steps = prefix.end(), []
    assignment = re.compile(r"\s*(s|d|\*sign|\*digit)\s*=\s*([^;]+);")
    while match := assignment.match(fragment, position):
        steps.append((match[1], ast.parse(re.sub(r"\bin\b", "input", " ".join(match[2].split())), mode="eval").body))
        position = match.end()
    if fragment[position:].strip() or [lhs for lhs, _ in steps] != ["s", "d", "d", "d", "*sign", "*digit"]:
        raise ValueError("Unmodeled Booth statements")
    return steps


def word_expr(node, names):
    if isinstance(node, ast.Constant) and isinstance(node.value, int):
        return f"({node.value} : BitVec 32)"
    if isinstance(node, ast.Name):
        return f"({names[node.id]}.setWidth 32)"
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Invert):
        return f"(~~~{word_expr(node.operand, names)})"
    if isinstance(node, ast.BinOp):
        left = word_expr(node.left, names)
        if isinstance(node.op, (ast.LShift, ast.RShift)):
            n = ast.literal_eval(node.right)
            if not 0 <= n < 32:
                raise ValueError("Undefined scalar shift")
            return f"({left} {'<<<' if isinstance(node.op, ast.LShift) else '>>>'} {n})"
        op = {ast.Add: "+", ast.Sub: "-", ast.BitAnd: "&&&", ast.BitOr: "|||"}.get(type(node.op))
        if op is None:
            raise ValueError("Unsupported scalar expression")
        return f"({left} {op} {word_expr(node.right, names)})"
    raise ValueError(f"Unsupported scalar expression: {ast.dump(node)}")


def generate_recode(source):
    lines = ["-- Generated by generate_scalar.py from the Booth helper.", "import P384.WordSemantics", "",
             "set_option autoImplicit false", "", "namespace P384", "",
             "def machineBoothRecode (input : BitVec 8) : BitVec 8 × BitVec 8 :="]
    names = {"input": "input"}
    for i, (lhs, rhs) in enumerate(recode_steps(source)):
        variable = f"v{i}"
        lines.append(f"  let {variable} := ({word_expr(rhs, names)}).setWidth 8")
        names[lhs] = variable
    lines += [f"  ({names['*sign']}, {names['*digit']})", "", "end P384", ""]
    return "\n".join(lines)


def source_snapshot(source, util):
    result = {}
    for path, text, names in [(str(SOURCE.relative_to(HERE.parent.parent)), source,
                              ["get_bit", "select_point", "batch_mul", "point_double", "point_add",
                               "ossl_ec_GFp_nistp384_points_mul", "make_points_affine"]),
                             (str(UTIL.relative_to(HERE.parent.parent)), util,
                              ["ossl_ec_GFp_nistp_recode_scalar_bits",
                               "ossl_ec_GFp_nistp_points_make_affine_internal"])]:
        result[path] = {name: hashlib.sha256(re.sub(r"\s+", "", body(clean(text), name)).encode()).hexdigest()
                        for name in names}
    return result


def scalar_constants(source):
    arrays = []
    for name, dimensions in [("nistp384_curve_params", "[5]"), ("gmul", "[16][3]")]:
        pattern = rf"static const (?:felem_bytearray|felem) {name}{re.escape(dimensions)} = (\{{.*?\n\}});"
        match = re.search(pattern, clean(source), re.S)
        if match is None:
            raise ValueError(f"Missing scalar constant {name}")
        arrays.append(ast.literal_eval(match[1].replace("{", "[").replace("}", "]")))
    params, table = arrays
    if (len(params) != 5 or any(len(row) != 48 or any(type(v) is not int or not 0 <= v < 256 for v in row) for row in params)
            or len(table) != 16 or any(len(point) != 3 or any(len(row) != 7 or any(type(v) is not int or not 0 <= v < 2**64 for v in row) for row in point) for point in table)):
        raise ValueError("Unexpected scalar constant dimensions or widths")
    return [int.from_bytes(bytes(row), "big") for row in params], table


def generate_constants(source):
    params, table = scalar_constants(source)
    lines = ["-- Generated by generate_scalar.py from the C scalar constants.",
             "import P384.WordSemantics", "", "set_option autoImplicit false",
             "set_option maxRecDepth 32768", "", "namespace P384", "",
             "def scalarCurveParams : Fin 5 → ℕ :=", "  ![" + ", ".join(map(str, params)) + "]", "",
             "def builtinGeneratorWords : Fin 16 → Fin 21 → BitVec 64 :=", "  !["]
    for i, point in enumerate(table):
        lines.append("    ![" + ", ".join(str(v) for row in point for v in row) + "]" + ("," if i < 15 else "]"))
    return "\n".join(lines + ["", "end P384", ""])


def generate_doublings(source):
    params, _ = scalar_constants(source)
    prime, x, y = params[0], params[3], params[4]
    points = [(x, y)]
    for _ in range(285):
        slope = (3*x*x - 3) * pow(2*y, -1, prime) % prime
        u = (slope*slope - 2*x) % prime
        y = (slope*(x-u) - y) % prime
        x = u
        points.append((x, y))
    lines = ["-- Generated witness coordinates; ScalarTable.lean verifies every step.",
             "import P384.WordSemantics", "", "set_option autoImplicit false",
             "set_option maxRecDepth 32768", "", "namespace P384", "",
             "def generatorDoublingData : Fin 286 → ℕ × ℕ :=", "  !["]
    for i, (x, y) in enumerate(points):
        lines.append(f"    ({x}, {y})" + ("," if i < 285 else "]"))
    return "\n".join(lines + ["", "end P384", ""])


def generate_output(source):
    fragment = re.sub(r"\s+", "", body(clean(source), "batch_mul"))
    declaration = "widefelemwide_y={0};"
    tail = ("felem_assign(x_out,nq[0]);"
            "for(i=0;i<NLIMBS;i++)wide_y[i]=nq[1][i];"
            "felem_reduce(y_out,wide_y);"
            "felem_assign(z_out,nq[2]);")
    if fragment.count(declaration) != 1 or fragment.count("wide_y") != 3 or not fragment.endswith(tail):
        raise ValueError("Unexpected scalar output normalization")
    if re.search(r"^\s*#define\s+NLIMBS\s+7\s*$", source, re.M) is None:
        raise ValueError("Unexpected scalar limb count")
    return "\n".join([
        "-- Generated by generate_scalar.py from the batch_mul output stage.",
        "import P384.GeneratedMachine", "", "set_option autoImplicit false", "", "namespace P384", "",
        "def scalarOutputWide (a : LimbWords) : WideWords :=",
        "  ![" + ", ".join(f"(a {i}).setWidth 128" for i in range(7)) + ", 0, 0, 0, 0, 0, 0]", "",
        "def machineScalarOutputY (a : LimbWords) : LimbWords := machineReduce (scalarOutputWide a)",
        "", "end P384", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, util = SOURCE.read_text(), UTIL.read_text()
    outputs = {HERE / "P384/GeneratedBooth.lean": generate_recode(util),
               HERE / "P384/GeneratedScalarConstants.lean": generate_constants(source),
               HERE / "P384/GeneratedGeneratorWitness.lean": generate_doublings(source),
               HERE / "P384/GeneratedScalarOutput.lean": generate_output(source)}
    snapshot = HERE / "scalar-sources.json"
    fingerprints = source_snapshot(source, util)
    if args.check:
        if any(path.read_text() != text for path, text in outputs.items()) or json.loads(snapshot.read_text())["functions"] != fingerprints:
            raise SystemExit("Scalar source or extracted model changed")
        print("Scalar helper model and reviewed source snapshot match")
    else:
        for path, text in outputs.items():
            path.write_text(text)
        snapshot.write_text(json.dumps({"boundary": "Hand-translated batch schedule; unverified C frontend",
                                        "functions": fingerprints}, indent=2) + "\n")


if __name__ == "__main__":
    main()
